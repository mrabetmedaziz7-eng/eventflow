CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'EN_ATTENTE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_status CHECK (status IN ('EN_ATTENTE', 'ACTIF', 'REFUSE', 'DESACTIVE'))
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    category VARCHAR(100) NOT NULL,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    location VARCHAR(255) NOT NULL,
    image_url TEXT,
    ticket_price NUMERIC(12, 2) NOT NULL,
    capacity INTEGER NOT NULL,
    available_places INTEGER NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'BROUILLON',
    teacher_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_events_teacher FOREIGN KEY (teacher_id) REFERENCES users (id),
    CONSTRAINT chk_events_ticket_price CHECK (ticket_price > 0),
    CONSTRAINT chk_events_capacity CHECK (capacity > 0),
    CONSTRAINT chk_events_available_places CHECK (available_places >= 0 AND available_places <= capacity),
    CONSTRAINT chk_events_status CHECK (status IN ('BROUILLON', 'PUBLIE', 'COMPLET', 'ANNULE', 'TERMINE'))
);

CREATE TABLE event_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    action_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_event_actions_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT uq_event_actions_display_order UNIQUE (event_id, display_order),
    CONSTRAINT chk_event_actions_display_order CHECK (display_order >= 0)
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    reservation_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(24) NOT NULL DEFAULT 'EN_ATTENTE',
    number_of_places INTEGER NOT NULL,
    confirmation_code VARCHAR(100),
    CONSTRAINT fk_reservations_student FOREIGN KEY (student_id) REFERENCES users (id),
    CONSTRAINT fk_reservations_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT uq_reservations_confirmation_code UNIQUE (confirmation_code),
    CONSTRAINT chk_reservations_number_of_places CHECK (number_of_places > 0),
    CONSTRAINT chk_reservations_status CHECK (status IN ('EN_ATTENTE', 'CONFIRMEE', 'ANNULEE', 'EXPIREE'))
);

CREATE UNIQUE INDEX uq_reservations_active_student_event
    ON reservations (student_id, event_id)
    WHERE status IN ('EN_ATTENTE', 'CONFIRMEE');

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    payment_date TIMESTAMPTZ,
    method VARCHAR(40) NOT NULL,
    reference VARCHAR(255),
    status VARCHAR(24) NOT NULL DEFAULT 'EN_ATTENTE',
    CONSTRAINT fk_payments_reservation FOREIGN KEY (reservation_id) REFERENCES reservations (id),
    CONSTRAINT uq_payments_reservation UNIQUE (reservation_id),
    CONSTRAINT chk_payments_amount CHECK (amount > 0),
    CONSTRAINT chk_payments_status CHECK (status IN ('EN_ATTENTE', 'PAYE', 'ECHOUE', 'REMBOURSE'))
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    action_type VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100) NOT NULL,
    entity_id BIGINT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_logs_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_events_event_date ON events (event_date);
CREATE INDEX idx_events_category ON events (category);
CREATE INDEX idx_events_status ON events (status);
CREATE INDEX idx_events_location ON events (location);
CREATE INDEX idx_events_title ON events (title);
CREATE INDEX idx_events_teacher_id ON events (teacher_id);
CREATE INDEX idx_event_actions_event_id ON event_actions (event_id);
CREATE INDEX idx_reservations_student_id ON reservations (student_id);
CREATE INDEX idx_reservations_event_id ON reservations (event_id);
CREATE INDEX idx_reservations_status ON reservations (status);
CREATE INDEX idx_payments_status ON payments (status);
CREATE INDEX idx_notifications_user_read_created ON notifications (user_id, is_read, created_at);
CREATE INDEX idx_audit_logs_user_created ON audit_logs (user_id, created_at);
